"""
Задание 9: Счастливых часов не наблюдают

Напишите программу, которая:
1. Запрашивает время прихода (часы, минуты, секунды)
2. Запрашивает время ухода (часы, минуты, секунды)
3. Вычисляет разницу во времени
4. Выводит в формате "часы:минуты:секунды"

Пример:
Час прихода: 9
Минута прихода: 0
Секунда прихода: 0
Час ухода: 12
Минута ухода: 30
Секунда ухода: 0
3:30:00
"""

hoa = int(input("Час прихода: "))
moa = int(input("Минута прихода: "))
soa = int(input("Секунда прихода: "))
hol = int(input("Час ухода: "))
mol = int(input("Минута ухода: "))
sol = int(input("Секунда ухода: "))

seconds = (hol*3600 + mol*60 + sol) - (hoa*3600 + moa*60 + soa)
print(f"{seconds//3600}:{str(seconds%3600//60).rjust(2,'0')}:{str(seconds%60).rjust(2,'0')}")
