"""
Задание 9: Счастливых часов не наблюдают

Напишите программу, которая:
1. Запрашивает время прихода (часы, минуты, секунды)
2. Запрашивает время ухода (часы, минуты, секунды)
3. Вычисляет разницу во времени
4. Выводит в формате "часы:минуты:секунды"

Пример:
Час прихода: 9
Минута прихода: 0
Секунда прихода: 0
Час ухода: 12
Минута ухода: 30
Секунда ухода: 0
3:30:00
"""

h = int(input('Час прихода:'))
m = int(input('Минута прихода:'))
s = int(input('Секунда прихода:'))
h2 = int(input('Час ухода:'))
m2 = int(input('Минута ухода:'))
s2 = int(input('Секунда ухода:'))
start = h * 3600 + m * 60 + s
end = h2 * 3600 + m2 * 60 + s2
r = abs(start - end)
hours = r // 3600
minutes = (r % 3600) // 60
seconds = r % 60
print(f'{hours}:{minutes}:{seconds}')
