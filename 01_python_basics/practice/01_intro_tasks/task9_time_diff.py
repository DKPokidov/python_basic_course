"""
Задание 9: Счастливых часов не наблюдают

Напишите программу, которая:
1. Запрашивает время прихода (часы, минуты, секунды)
2. Запрашивает время ухода (часы, минуты, секунды)
3. Вычисляет разницу во времени
4. Выводит в формате "часы:минуты:секунды"

Пример:
Час прихода: 9
Минута прихода: 0
Секунда прихода: 0
Час ухода: 12
Минута ухода: 30
Секунда ухода: 0
3:30:00
"""

# НАПИШИТЕ ВАШ КОД ЗДЕСЬ
h1 = int(input("Час прихода: "))
m1 = int(input("Минута прихода: "))
s1 = int(input("Секунда прихода: "))

h2 = int(input("Час ухода: "))
m2 = int(input("Минута ухода: "))
s2 = int(input("Секунда ухода: "))

start = h1 * 3600 + m1 * 60 + s1
end = h2 * 3600 + m2 * 60 + s2

# Разница с добавлением 24 часов, если нужно
diff = (end - start) % (24 * 3600)

hours = diff // 3600
minutes = (diff % 3600) // 60
seconds = diff % 60

print(f"{hours}:{minutes:02d}:{seconds:02d}")