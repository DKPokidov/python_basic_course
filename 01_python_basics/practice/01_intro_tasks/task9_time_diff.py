"""
Задание 9: Счастливых часов не наблюдают

Напишите программу, которая:
1. Запрашивает время прихода (часы, минуты, секунды)
2. Запрашивает время ухода (часы, минуты, секунды)
3. Вычисляет разницу во времени
4. Выводит в формате "часы:минуты:секунды"

Пример:
Час прихода: 9
Минута прихода: 0
Секунда прихода: 0
Час ухода: 12
Минута ухода: 30
Секунда ухода: 0
3:30:00
"""
a=int(input('Час прихода: '))
b=int(input('Минута прихода: '))
c=int(input('Секунда прихода: '))
a2=int(input('Час ухода: '))
b2=int(input('Минута ухода: '))
c2=int(input('Секунда ухода: '))
a3=abs(a-a2)
b3=abs(b-b2)
c3=abs(c-c2)
print(f'{a3}:{b3}:{c3}')
