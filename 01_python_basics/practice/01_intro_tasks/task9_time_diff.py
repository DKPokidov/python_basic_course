"""
Задание 9: Счастливых часов не наблюдают

Напишите программу, которая:
1. Запрашивает время прихода (часы, минуты, секунды)
2. Запрашивает время ухода (часы, минуты, секунды)
3. Вычисляет разницу во времени
4. Выводит в формате "часы:минуты:секунды"

Пример:
Час прихода: 9
Минута прихода: 0
Секунда прихода: 0
Час ухода: 12
Минута ухода: 30
Секунда ухода: 0
3:30:00
"""
hours1 = int(input('Час прихода: '))
minuts1 = int(input('Секунда прихода: '))
sek1  = int(input('Секунда прихода: '))
hours2 = int(input('Час ухода: '))
minuts2 = int(input('Минута ухода: '))
sek2  = int(input('Секунда ухода: '))
razn = (sek2 + minuts2*60 + hours2*3600) - (sek1 + minuts1*60 + hours1*3600)
print(f'{razn // 3600}:{((razn % 3600) // 60):02d}:{(razn % 60):02d}' )
