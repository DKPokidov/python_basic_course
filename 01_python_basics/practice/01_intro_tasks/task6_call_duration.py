"""
Задание 6: Миша и его деньги

Напишите программу, которая:
1. Запрашивает баланс до разговора (рубли)
2. Запрашивает баланс после разговора (рубли)
3. Стоимость минуты: 2.5 руб (2 руб 50 коп)
4. Вычисляет длительность разговора в минутах
5. Выводит: "Разговор длился {минуты} минут"

Примечание: все числовые значения — дробные (float).
Для ввода используйте float(input()), а не int(input()).

Пример:
Баланс до разговора (руб): 53.0
Баланс после разговора (руб): 8.0
Разговор длился 18 минут
"""

x = [float(input("до разговора (руб)")), float(input("после разговора (руб)"))]

def Calltime(price, x):
    return -1 * (x[1] - x[0]) / price


print(f"Разговор длился {Calltime(2.5, x):.0f} минут")