"""
Задание 2: Помощь чиновнику

Напишите программу, которая:
1. Запрашивает длину сквера в метрах
2. Запрашивает ширину сквера в метрах
3. Вычисляет площадь сквера (длина * ширина)
4. Выводит: "Площадь озеленения: {площадь} кв.м"

Пример:
Введите длину сквера (м): 10
Введите ширину сквера (м): 5
Площадь озеленения: 50.0 кв.м
"""
# Запрашиваем длину сквера
length = float(input("Введите длину сквера (м): "))

# Запрашиваем ширину сквера
width = float(input("Введите ширину сквера (м): "))

# Вычисляем площадь
area = length * width

# Выводим результат
print(f"Площадь озеленения: {area} кв.м")