"""
Задание 4: Международный весооборот

Напишите программу, которая:
1. Запрашивает вес и единицу измерения (кг, г, фунт, пуд, ц, т)
2. Переводит вес в килограммы
3. Выводит: "{вес} {единица} = {результат} кг"

Коэффициенты перевода в кг:
- 1 кг = 1 кг
- 1 г = 0.001 кг
- 1 фунт = 0.40951241 кг
- 1 пуд = 16 кг
- 1 ц = 100 кг
- 1 т = 1000 кг

Пример:
Введите вес и единицу измерения (например, '10 кг'): 1 т
1.0 т = 1000.000000 кг
"""
# Коэффициенты перевода в килограммы
conversion = {
    "кг": 1,
    "г": 0.001,
    "фунт": 0.40951241,
    "пуд": 16,
    "ц": 100,
    "т": 1000
}

# Запрашиваем ввод
user_input = input("Введите вес и единицу измерения (например, '10 кг'): ")

# Разделяем строку на число и единицу измерения
parts = user_input.split()
weight = float(parts[0])
unit = parts[1]

# Переводим в килограммы
result = weight / conversion[unit]

# Выводим результат с 6 знаками после запятой
print(f"{weight} {unit} = {result:.6f} кг")