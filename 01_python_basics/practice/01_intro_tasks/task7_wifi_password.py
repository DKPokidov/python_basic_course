"""
Задание 7: Тайный код от Wi-Fi

Напишите программу, которая:
1. Запрашивает трёхзначное число
2. Разбивает его на цифры (сотни, десятки, единицы)
3. Выводит цифры через точку: "сотни.десятки.единицы"

Пример:
Введите трёхзначное число: 789
7.8.9
"""

# НАПИШИТЕ ВАШ КОД ЗДЕСЬ
number = int(input("Введите трёхзначное число: "))

hundreds = number // 100
tens = (number // 10) % 10
ones = number % 10

print(f"{hundreds}.{tens}.{ones}")
