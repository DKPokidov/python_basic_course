"""
Задание 3: Счет мелких денег

Напишите программу, которая:
1. Запрашивает количество монет по 50 копеек
2. Запрашивает количество монет по 10 копеек
3. Запрашивает количество монет по 5 копеек
4. Запрашивает количество монет по 1 копейке
5. Вычисляет общую сумму в рублях и копейках
6. Выводит: "{рубли} руб. {копейки} коп."

Пример:
Сколько монет по 50 копеек? 1
Сколько монет по 10 копеек? 2
Сколько монет по 5 копеек? 3
Сколько монет по 1 копейке? 4
0 руб. 89 коп.
"""
# Запрашиваем количество монет каждого номинала
coins_50 = int(input("Сколько монет по 50 копеек? "))
coins_10 = int(input("Сколько монет по 10 копеек? "))
coins_5 = int(input("Сколько монет по 5 копеек? "))
coins_1 = int(input("Сколько монет по 1 копейке? "))

# Вычисляем общую сумму в копейках
total_kopecks = coins_50 * 50 + coins_10 * 10 + coins_5 * 5 + coins_1 * 1

# Переводим в рубли и копейки
rubles = total_kopecks // 100
kopecks = total_kopecks % 100

# Выводим результат
print(f"{rubles} руб. {kopecks} коп.")