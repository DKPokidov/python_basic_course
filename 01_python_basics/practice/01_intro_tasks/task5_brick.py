"""
Задание 5: Кирпич

Напишите программу, которая:
1. Запрашивает длину кирпича (см)
2. Запрашивает ширину кирпича (см)
3. Запрашивает высоту кирпича (см)
4. Вычисляет и выводит:
   - Объём (см³): длина * ширина * высота
   - Площадь поверхности (см²): 2 * (д*ш + ш*в + д*в)
   - Сумму рёбер (см): 4 * (д + ш + в)
   - Массу (кг): объём(м³) * 1700
   - Количество кирпичей в 1 м³
"""

# Запрашиваем размеры кирпича
length = float(input("Введите длину кирпича (см): "))
width = float(input("Введите ширину кирпича (см): "))
height = float(input("Введите высоту кирпича (см): "))

# Вычисляем объём в см³
volume_cm3 = length * width * height

# Вычисляем площадь поверхности
surface_area = 2 * (length * width + width * height + length * height)

# Вычисляем сумму рёбер
edges_sum = 4 * (length + width + height)

# Вычисляем объём в м³ (1 м³ = 1 000 000 см³)
volume_m3 = volume_cm3 / 1_000_000

# Вычисляем массу (плотность кирпича ≈ 1700 кг/м³)
mass = volume_m3 * 1700

# Вычисляем количество кирпичей в 1 м³
# (1 м³ / объём одного кирпича в м³)
bricks_per_m3 = int(1 / volume_m3)

# Выводим результаты
print(f"Объём: {volume_cm3:.1f} см³")
print(f"Площадь поверхности: {surface_area:.1f} см²")
print(f"Сумма рёбер: {edges_sum:.1f} см")
print(f"Масса: {mass:.2f} кг")
print(f"Количество кирпичей в 1 м³: {bricks_per_m3}")
