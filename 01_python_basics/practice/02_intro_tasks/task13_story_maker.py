"""
Задание 13: Сочинитель сказок

Вы очень любите своего младшего брата. 
Родители поручили вам читать ему сказки на ночь. 
Напишите программу, которая создаёт забавную историю с пропусками.

Программа должна последовательно:
1. Запросить имя хомяка
2. Запросить любимую еду
3. Запросить профессию
4. Запросить навык
5. Запросить город
6. Запросить персонажа
7. Запросить фразу персонажа
8. Запросить ответ хомяка
9. Запросить прилагательное
10. Вывести готовую историю

Пример вывода:
Жил-был хомяк по имени Дедди
Дедди очень любил есть котлеты и мечтал стать ученым
Однажды Дедди научился делать опыты над хомяками и отправился в Воронеж
Воронеж его встретил Ворон, который сказал: "Привет, дружище!"
"Привет!" — и с тех пор Дедди стал самым ученым хомяком в мире!
"""
hamster_name = input("Введите имя хомяка: ")
favorite_food = input("Введите любимую еду хомяка: ")
profession = input("Введите профессию, которой мечтает овладеть хомяк: ")
skill = input("Введите навык, который хомяк научился делать: ")
city = input("Введите город, куда отправился хомяк: ")
character = input("Введите имя персонажа, которого встретил хомяк: ")
phrase = input("Какую фразу сказал этот персонаж: ")
hamster_reply = input("Что ответил хомяк: ")
adjective = input("Введите прилагательное, которое описывает хомяка в конце истории: ")
print(
    f"Жил-был хомяк по имени {hamster_name}.\n"
    f"{hamster_name} очень любил есть {favorite_food} и мечтал стать {profession}.\n"
    f"Однажды {hamster_name} научился {skill} и отправился в {city}.\n"
    f"{city} его встретил {character}, который сказал: \"{phrase}\"\n"
    f"\"{hamster_reply}\" — и с тех пор {hamster_name} стал самым {adjective} хомяком в мире!"
)