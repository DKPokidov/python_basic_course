"""
Задание 14: Злая формула

Напишите программу, которая вычисляет значение формулы и выводит ответ.

Формула: 
    (m * n) / (m + n) + (m - n) / (m * n)

Программа должна:
1. Запросить значение m
2. Запросить значение n
3. Вычислить результат по формуле
4. Вывести: "Ответ: {результат}"

Пример:
Введите m: 5
Введите n: 3
Ответ: 1.875 + 0.133 = 2.008

Примечание: используйте float() для ввода чисел
"""
m = float(input("Введите m: "))
n = float(input("Введите n: "))
r1 = (m * n) / (m + n)
r2 = (m - n) / (m * n)
result = r1 + r2
print(f"Ответ: {r1} + {r2} = {result}")