"""
Задание 11: Оценка загруженности автобусных остановок

Вам дан список остановок общественного транспорта. Для каждой известны:

* название;
* количество пассажиров, входящих за час;
* количество выходящих за час.

Нужно:

1. Для каждой остановки вычислить чистый пассажиропоток (входящие − выходящие).
2. Классифицировать остановку по потоку:

   * если поток > 50 → 'Высокая загруженность';
   * если 10 ≤ поток ≤ 50 → 'Средняя загруженность';
   * если поток < 10 → 'Низкая загруженность'.

3. Вывести название остановки, чистый поток и категорию.
"""

# НАПИШИТЕ ВАШ КОД ЗДЕСЬ
# 03_control_flow/practice/02_control_flow_tasks/task11_stop_load.py

stops = [
    {"name": "Центральная", "in": 120, "out": 60},
    {"name": "Заводская", "in": 30, "out": 25},
    {"name": "Парк", "in": 15, "out": 20},
    {"name": "Университет", "in": 80, "out": 30}
]

for stop in stops:
    flow = stop["in"] - stop["out"]  # чистый пассажиропоток

    if flow > 50:
        category = "Высокая загруженность"
    elif 10 <= flow <= 50:
        category = "Средняя загруженность"
    else:
        category = "Низкая загруженность"

    print(f"{stop['name']}: {flow}, {category}")
