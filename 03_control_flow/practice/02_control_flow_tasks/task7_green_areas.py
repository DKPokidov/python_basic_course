"""
Задание 7: Суммарная площадь зелёных зон

В городе 5 районов. Для каждого известен список площадей зелёных зон
(парков, скверов) в гектарах. Нужно написать программу, которая:

* переберёт все районы;
* для каждого района посчитает суммарную площадь зелёных зон;
* выведет результат по каждому району.
"""

# НАПИШИТЕ ВАШ КОД ЗДЕСЬ
# 03_control_flow/practice/02_control_flow_tasks/task7_green_areas.py

green_areas = {
    "Центральный": [2.5, 1.8, 0.7],
    "Северный": [4.2, 3.1],
    "Южный": [1.5, 1.5, 2.0],
    "Западный": [5.0],
    "Восточный": [3.3, 2.7, 1.0]
}

for district, areas in green_areas.items():
    total_area = sum(areas)  # сумма всех площадей в районе
    print(f"{district}: {total_area} га")
