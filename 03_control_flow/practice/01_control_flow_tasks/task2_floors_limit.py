"""
Задание 2: Подсчёт этажей с учётом ограничений

В городе действует ограничение:

* в исторической зоне — не выше 5 этажей;
* в новой застройке — не выше 20 этажей.

Программа:

1. Запрашивает зону («историческая» или «новая»).
2. Запрашивает количество этажей.
3. С помощью ветвления проверяет, соответствует ли этажность норме.
4. Выводит: «Допустимо» или «Превышение нормы!».
"""

# НАПИШИТЕ ВАШ КОД ЗДЕСЬ
# 03_control_flow/practice/01_control_flow_tasks/task2_floors_limit.py

zone = input("Зона (историческая/новая): ").lower()
floors = int(input("Количество этажей: "))

if zone == "историческая" and floors <= 5:
    print("Допустимо")
elif zone == "новая" and floors <= 20:
    print("Допустимо")
else:
    print("Превышение нормы!")
