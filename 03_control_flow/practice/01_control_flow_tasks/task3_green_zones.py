"""
Задание 3: Распределение зелёных зон по районам

Есть 3 района города с разной площадью зелёных зон (в га):

* район A: 150 га;
* район B: 80 га;
* район C: 200 га.

Программа перебирает районы. Для каждого района:

1. Если площадь >= 150 га → выводит «Высокий уровень озеленения»;
2. Если 50 <= площадь < 150 → «Средний уровень»;
3. Иначе → «Низкий уровень».
"""

# НАПИШИТЕ ВАШ КОД ЗДЕСЬ
# 03_control_flow/practice/01_control_flow_tasks/task3_green_zones.py

areas = {"A": 150, "B": 80, "C": 200}

for district, green_area in areas.items():
    if green_area >= 150:
        level = "Высокий уровень озеленения"
    elif green_area >= 50:
        level = "Средний уровень"
    else:
        level = "Низкий уровень"
    print(f"Район {district}: {level}")
