"""
Задание 3: Распределение зелёных зон по районам

Есть 3 района города с разной площадью зелёных зон (в га):

* район A: 150 га;
* район B: 80 га;
* район C: 200 га.

Программа перебирает районы. Для каждого района:

1. Если площадь >= 150 га → уровень «Высокий уровень озеленения»;
2. Если 50 <= площадь < 150 → «Средний уровень»;
3. Иначе → «Низкий уровень».

Для каждого района выведите строку в формате:

    Район <буква>: <уровень>

Например: «Район A: Высокий уровень озеленения», «Район B: Средний уровень».
"""
district = {
    "Район A" : 150,
    "Район B" : 80,
    "Район C" : 200,
}
for name, area in district.items():
    if area >= 150:
        level = "Высокий уровень озеленения"
    elif area >= 50:
        level = "Средний уровень"
    else:
        level = "Низкий уровень"
    print(f"{name}: {level}")
