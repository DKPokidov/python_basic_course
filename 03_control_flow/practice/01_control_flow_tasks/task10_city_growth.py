"""
Задание 10: Моделирование роста города с ограничениями

Замоделируйте рост населения города. Считаем, что введённое пользователем число —
население на начало 2024 года (в тыс. чел.). Каждый следующий год население
увеличивается на 5 % по формуле:

    население = int(население * 1.05)

(дробная часть отбрасывается, результат всегда целое число).

Что нужно:

1. Запросить у пользователя начальное население (в тыс. чел.).
2. Промоделировать 30 лет: с 2025 по 2054 год включительно.
3. Для каждого года вывести строку в формате:

    Год <год>: население <население> тыс. чел.

   Например: «Год 2029: население 1020 тыс. чел.».
4. Если после очередного шага население стало >= 1000 (1 млн чел.) — вывести
   «Город достиг миллиона жителей в <год> году!» и прекратить моделирование.
5. Если за 30 лет миллион так и не набран — вывести
   «За 30 лет город не достиг миллиона жителей.».
"""
bevolkerung = int(input('Введите количество населения тыс. чел '))
for i in range(30):
    bevolkerung = int(bevolkerung * 1.05)
    if bevolkerung >= 1000:
        print(f'Год {2024 + 1 + i}: население {bevolkerung} тыс. чел.')
        print(f'Город достиг миллиона жителей в {2024 + i + 1} году!')
        break
    else:
        print(f'Год {2024 + 1 + i}: население {bevolkerung} тыс. чел.')
if bevolkerung < 1000:
    print('За 30 лет город не достиг миллиона жителей.')
