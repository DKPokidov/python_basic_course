"""
Задание 10: Моделирование роста города с ограничениями

Замоделируйте рост населения города на 30 лет (с 2025 по 2055).
Каждый год население увеличивается на 5 %.

Что нужно:

* запросить у пользователя начальное население (в тыс. чел.);
* в цикле while вывести население за каждый год (округляя до целых тыс.);
* если население достигнет 1 млн чел. раньше 2055 года — сообщить об этом;
* если за 30 лет миллион не набран — вывести соответствующее сообщение.
"""

# НАПИШИТЕ ВАШ КОД ЗДЕСЬ
# 03_control_flow/practice/01_control_flow_tasks/task10_city_growth.py

population = float(input("Начальное население (тыс. чел.): "))
year = 2025
end_year = 2055
reached_million = False

while year < end_year and not reached_million:
    population = int(population * 1.05)  # +5%, округление до целых
    print(f"Год {year}: население {population} тыс. чел.")

    if population >= 1000:
        reached_million = True
        print(f"Город достиг миллиона жителей в {year} году!")

    year += 1

if not reached_million:
    print("За 30 лет город не достиг миллиона жителей.")
