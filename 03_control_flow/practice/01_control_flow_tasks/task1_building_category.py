"""
Задание 1: Проверка категории здания

Программа запрашивает тип здания (например, «школа», «торговый центр», «жилой дом»)
и определяет его категорию:

* «школа», «детский сад», «университет» → «Образовательное учреждение»;
* «торговый центр», «магазин» → «Торговое помещение»;
* «жилой дом», «апартаменты» → «Жилое здание»;
* всё остальное → «Иное сооружение».

Ввод может быть в любом регистре («Школа», «ШКОЛА», «школа») — перед сравнением
приведите его к нижнему регистру методом lower().

Результат выведите в формате:

    Категория: <название категории>

Например: «Категория: Образовательное учреждение», «Категория: Иное сооружение».
"""

building = str(input('Введите тип здания: '))
building = building.lower()
buildings = {
    'школа': 'Образовательное учреждение',
    'детский сад': 'Образовательное учреждение',
    'университет': 'Образовательное учреждение',
    'торговый центр': 'Торговое помещение',
    'магазин': 'Торговое помещение',
    'жилой дом': 'Жилое здание',
    'апартаменты': 'Жилое здание'
}
answer = buildings.get(building, 'Иное сооружение')
print('Категория:', answer)
