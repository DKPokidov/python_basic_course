"""
Задание 1: Классификация зданий

Программа принимает тип здания и выводит категорию.
"""

building_type = input("Введите тип здания: ")

if building_type == "школа":
    print("Образовательное учреждение")
elif building_type == "больница":
    print("Медицинское учреждение")
elif building_type == "офис":
    print("Деловое здание")
else:
    print("Иное назначение")