"""
Задание 8: Поиск районов с высокой плотностью населения

Есть список районов с данными: площадь (км²) и численность населения (тыс. чел.). Нужно:

* в цикле перебрать все районы;
* для каждого вычислить плотность населения (население / площадь);
* если плотность превышает 5 тыс. чел./км², добавить район в список «плотно заселённых»;
* в конце вывести список таких районов.
"""

# НАПИШИТЕ ВАШ КОД ЗДЕСЬ
# 03_control_flow/practice/02_control_flow_tasks/task8_dense_districts.py

districts_data = [
    ("Центр", 10, 60),      # площадь 10 км², население 60 тыс. чел.
    ("Спальный", 25, 80),   # площадь 25 км², население 80 тыс. чел.
    ("Промзона", 15, 45),   # площадь 15 км², население 45 тыс. чел.
    ("Новый", 30, 75),      # площадь 30 км², население 75 тыс. чел.
    ("Старый", 8, 50)       # площадь 8 км², население 50 тыс. чел.
]

dense_districts = []  # список плотно заселённых районов

for name, area, population in districts_data:
    density = population / area  # плотность: тыс. чел. на км²
    if density > 5:
        dense_districts.append(name)

print("Плотно заселённые районы:", dense_districts)
