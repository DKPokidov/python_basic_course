"""
Задание 5: Генератор урбанистических слоганов

Создайте генератор слоганов для новых городских проектов, смешивая готовые фразы.

Программа должна:
1. Спросить у пользователя индекс для каждой части слогана (0-3)
2. Собрать слоган по формуле: starts[i] + " " + middles[j] + " " + ends[k]
3. Вывести результат
"""

# НАПИШИТЕ ВАШ КОД ЗДЕСЬ
# 02_python_structures/practice/01_structures_tasks/task5_slogan.py

# База данных креативных фраз
starts = ["Инновационный", "Экологичный", "Цифровой", "Комфортный"]
middles = ["городской", "общественный", "арт", "умный"]
ends = ["ландшафт", "транспорт", "парк", "квартал"]

# Запрашиваем индексы у пользователя
i = int(input("Выберите начало (0-3): "))
j = int(input("Выберите середину (0-3): "))
k = int(input("Выберите конец (0-3): "))

# Собираем слоган
slogan = starts[i] + " " + middles[j] + " " + ends[k]

print("Ваш слоган:", slogan)
