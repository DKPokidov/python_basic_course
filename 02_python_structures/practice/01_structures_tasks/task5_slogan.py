"""
Задание 5: Генератор урбанистических слоганов

Создайте генератор слоганов для новых городских проектов, смешивая готовые фразы.

Готовые списки частей слогана starts, middles и ends уже заданы.

Программа должна:
1. Спросить у пользователя индекс для каждой части слогана (0-3)
2. Собрать слоган по формуле: starts[i] + " " + middles[j] + " " + ends[k]
3. Вывести результат
"""

starts = ["Инновационный", "Экологичный", "Передовой", "Комфортный"]
middles = ["городской", "зелёный", "арт", "умный"]
ends = ["ландшафт", "двор", "пространство", "квартал"]
i = int(input('Введите индекс 1 (0-3): '))
j = int(input('Введите индекс 2 (0-3): '))
k = int(input('Введите индекс 3 (0-3): '))

say = str(starts[i] + " " + middles[j] + " " + ends[k])
print(say)
