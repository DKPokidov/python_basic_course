"""
Задание 8: Название улицы

В системе градостроительного учёта длина названия улицы не должна превышать 30 символов.
Дано название улицы в виде строки. Используя логические операции, проверьте:

* длина <= 30 символов И строка не пустая.

Выведите True, если оба условия выполнены, иначе False.
"""
name_of_street = input("Введите название улицы: ")
if len(name_of_street) <= 30 and len(name_of_street) > 0:
    print(True)
else:
    print(False) 