"""
Задание 3: Рейтинг кофеен вокруг университета

Студенты-урбанисты исследовали, где лучше всего готовят кофе для подготовки первого зачета.

1. Добавьте новую кофейню "Бессонный урбанист" с рейтингом 10
2. Увеличьте рейтинг "Цифербурга" на 1 (он стал ещё лучше!)
3. Выведите название кофейни с самым высоким рейтингом
"""

# НАПИШИТЕ ВАШ КОД ЗДЕСЬ
# 02_python_structures/practice/01_structures_tasks/task3_coffee_shops.py

# Словарь с рейтингами кофеен
coffee_shops = {
    "Starbucks у Кронверка": 7,
    "Цифербург": 9,
    "Кофейня на Биржевой": 6,
    "Академия кофе": 8
}

# Добавляем новую кофейню
coffee_shops["Бессонный дизайнер"] = 10

# Увеличиваем рейтинг Цифербурга
coffee_shops["Цифербург"] += 1

# Ищем кофейню с максимальным рейтингом
best_shop = max(coffee_shops, key=coffee_shops.get)  # метод словаря, который получает значение по ключу
best_rating = coffee_shops[best_shop]

print(f"Лучшая кофейня: {best_shop} с рейтингом {best_rating}")
