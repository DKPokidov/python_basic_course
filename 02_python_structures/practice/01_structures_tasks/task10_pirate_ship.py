"""
Задание 10: Пиратские корабли

Для защиты корабля капитан Сэм попросил бортинженера Тома реализовать автоматическое
распознавание кораблей пиратов острова "Island X".

Правила определения пиратского корабля:
* цвет флага — «черный»;
* рисунок на флаге — «череп» или Enter (пустая строка).

Программа должна выводить сообщение «Осторожно пираты!», если распознан пиратский корабль,
и «Корабль не опасен!», если не распознан.

Внимание: оператор If использовать запрещается.
"""

# НАПИШИТЕ ВАШ КОД ЗДЕСЬ
# 02_python_structures/practice/01_structures_tasks/task10_pirate_ship.py

print("=== СИСТЕМА ОПОЗНАНИЯ ПИРАТСКИХ КОРАБЛЕЙ ===")

# Ввод данных
color = input("Введите цвет флага: ")
drawing = input("Введите рисунок на флаге (череп или Enter если нет): ")

# Проверка условий с помощью логических операторов
is_black_flag = (color == "черный")
is_skull_or_empty = (drawing == "череп") or (drawing == "")

# Если ОБА условия True - это пиратский корабль
is_pirate = is_black_flag and is_skull_or_empty

# Преобразуем логическое значение в строку сообщения
message = "Осторожно пираты!" * is_pirate + "Корабль не опасен!" * (not is_pirate)

print(message)
