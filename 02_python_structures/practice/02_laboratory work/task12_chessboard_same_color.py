"""
Задание 12: Шахматная доска. Опять

Разработайте программу, которая получает на вход координаты двух клеток шахматной доски
x1, y1 и x2, y2 и проверяет истинность высказывания «эти клетки одинакового цвета».

Не используйте при решении этой задачи логические операции и конструкции ветвления,
их мы изучим позже, постарайтесь обойтись логическими переменными и арифметическими операциями.

Предполагается, что программа получает на вход целые числа в диапазоне от 1 до 8.
"""

# НАПИШИТЕ ВАШ КОД ЗДЕСЬ
# 02_python_structures/practice/01_structures_tasks/task12_chessboard_same_color.py

# Ввод координат первой клетки
x1 = int(input("Введите x1 (1-8): "))
y1 = int(input("Введите y1 (1-8): "))

# Ввод координат второй клетки
x2 = int(input("Введите x2 (1-8): "))
y2 = int(input("Введите y2 (1-8): "))

# Определяем цвета клеток через четность сумм координат
color1 = (x1 + y1) % 2  # 0 - черная, 1 - белая
color2 = (x2 + y2) % 2  # 0 - черная, 1 - белая

# Клетки одинакового цвета, если color1 == color2
# Используем математическое равенство: (a == b) -> (a - b == 0)
same_color = (color1 - color2) == 0

print("Клетки одинакового цвета:", same_color)
